#include <stdio.h>

int main() {
    char c = 'A';
    printf("'A' = %d\n", c);
    printf("'a' = %d\n", 'a');
    printf("'0' = %d\n", '0');
    printf("' ' = %d\n", ' ');
    printf("'\\n' = %d\n", '\n');

    printf("\n");

    printf("65 = %c\n", 65);
    printf("97 = %c\n", 97);
    printf("48 = %c\n", 48);

    return 0;
}
